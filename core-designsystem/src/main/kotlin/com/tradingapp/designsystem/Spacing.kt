package com.tradingapp.designsystem

import androidx.compose.ui.unit.dp

/**
 * Spacing scale for the Trading app design system.
 *
 * A named scale keeps padding values consistent and self-documenting rather
 * than scattering magic dp literals across composables.
 */
object Spacing {
    val xxs = 2.dp
    val xs = 4.dp
    val sm = 8.dp
    val md = 12.dp
    val lg = 16.dp
    val xl = 24.dp
    val xxl = 32.dp
    val xxxl = 48.dp
}
